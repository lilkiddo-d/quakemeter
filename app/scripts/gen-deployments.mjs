// Collects every app/src/config/generated/deployments.<chainId>.json written by the deploy script and emits
// app/src/config/deployments.generated.ts (a record keyed by chain id). Missing files => empty record, so the
// app always builds; the UI then shows "Contracts not deployed on this network yet".
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
// GEN_DEPLOYMENTS_DIR lets CI/tests point at another folder (e.g. an empty one).
const dir = process.env.GEN_DEPLOYMENTS_DIR || join(appRoot, "src", "config", "generated");
const outFile = join(appRoot, "src", "config", "deployments.generated.ts");

const record = {};
if (existsSync(dir)) {
  for (const f of readdirSync(dir)) {
    const m = /^deployments\.(\d+)\.json$/.exec(f);
    if (!m) continue;
    try {
      const data = JSON.parse(readFileSync(join(dir, f), "utf8"));
      record[m[1]] = data;
    } catch (e) {
      console.warn(`[gen-deployments] skipping ${f}: ${e.message}`);
    }
  }
}

mkdirSync(dirname(outFile), { recursive: true });
const body =
  "// Generated by app/scripts/gen-deployments.mjs — do not edit. Source: src/config/generated/deployments.*.json\n" +
  "/* eslint-disable */\n" +
  `export const RAW_DEPLOYMENTS: Record<string, unknown> = ${JSON.stringify(record, null, 2)};\n`;
writeFileSync(outFile, body);
const ids = Object.keys(record);
console.log(`[gen-deployments] ${ids.length ? "chains: " + ids.join(", ") : "no deployments found (UI will show not-deployed state)"}`);
